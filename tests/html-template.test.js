'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const rendered=require('./helpers/web-html')();
const generated=fs.readFileSync(path.join(root,'app/public/index.html'),'utf8');

assert.equal(generated,'<!-- Generated by scripts/build-web.js; edit apps/web instead. -->\n'+rendered);
assert.doesNotMatch(generated,/<!--\s*@(?:include|scripts)\b/);

const ids=[...generated.matchAll(/\bid="([^"]+)"/g)].map(match=>match[1]);
const duplicates=ids.filter((id,index)=>ids.indexOf(id)!==index);
assert.deepEqual([...new Set(duplicates)],[],'Generated HTML must not contain duplicate ids');

console.log('html template tests passed');
