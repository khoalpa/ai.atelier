const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync(path.join(__dirname,'../app/public/app.js'),'utf8');
const events=[];
const bar={hidden:true,scrollIntoView(options){events.push(['scroll',options]);}};
const primary={focus(options){events.push(['focus',options]);}};
const context={studioCommandCollapseTimer:42,studioCommandManuallyCollapsed:true,$:id=>id==='studioCommandBar'?bar:primary,clearTimeout:id=>events.push(['clear',id]),setStudioCommandCollapsed:collapsed=>events.push(['collapse',collapsed])};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function revealStudioCreateAction('),source.indexOf('function setStudioCommandCollapsed(')),context);
context.revealStudioCreateAction();
assert.equal(bar.hidden,false);
assert.equal(context.studioCommandCollapseTimer,null);
assert.equal(context.studioCommandManuallyCollapsed,false);
assert.deepEqual(events.map(event=>event[0]),['clear','collapse','scroll','focus']);
assert.equal(events[1][1],false);
assert.equal(events[3][1].preventScroll,true);
assert(source.includes('if(ready){revealStudioCreateAction();}'));
events.length=0;context.revealStudioCreateAction();
assert.equal(events[0][0],'collapse');
console.log('OK: navigation expands the action bar, cancels auto-collapse and focuses without a second scroll.');
