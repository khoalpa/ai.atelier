'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),home=path.join(root,'apps/web'),output=path.join(root,'app/public');
const manifest=JSON.parse(fs.readFileSync(path.join(home,'manifest.json'),'utf8'));
let bundle='// Generated by scripts/build-web.js; edit apps/web/core instead.\n(function bootstrapAtelier(){\n"use strict";\nconst context=globalThis.AtelierApp=globalThis.AtelierApp||{};\nconst modules={};\n';
for(const name of manifest.modules){
 const source=fs.readFileSync(path.join(home,'core',name+'.js'),'utf8');new vm.Script(source,{filename:name+'.js'});
 bundle+=`modules[${JSON.stringify(name)}]=(function(){const module={exports:{}};\n${source}\nreturn module.exports(context);})();\n`;
}
bundle+='for(const module of Object.values(modules))Object.defineProperties(context,Object.getOwnPropertyDescriptors(module.bindings));\n';
// Keep named handlers for existing inline controls; all state belongs to the
// module context, and feature scripts receive it explicitly through AtelierApp.
bundle+='for(const name of Object.keys(context)){if(typeof context[name]==="function"&&!(name in globalThis))Object.defineProperty(globalThis,name,{configurable:true,get:()=>context[name]});}\n';
for(const step of manifest.steps)bundle+=`modules[${JSON.stringify(step.module)}].steps[${step.step}]();\n`;
bundle+='globalThis.dispatchEvent(new Event("atelier:ready"));\n})();\n';
new vm.Script(bundle,{filename:'app.js'});fs.writeFileSync(path.join(output,'app.js'),bundle);
for(const file of manifest.features){
 const shared={'manual-core.js':'document.js','export-core.js':'export.js'}[file];
 fs.copyFileSync(file==='prompt-quality.js'?path.join(root,'packages/prompting/compiler.js'):shared?path.join(root,'packages/editor-core',shared):path.join(home,'features',file),path.join(output,file));
}
let html=fs.readFileSync(path.join(home,'index.html'),'utf8');html=html.replace('<script src="/ai-theme.js"></script>','<script src="/ai-theme.js"></script>\n  <script>window.AtelierApp={};</script>');fs.writeFileSync(path.join(output,'index.html'),html);
fs.cpSync(path.join(home,'styles'),path.join(output,'styles'),{recursive:true});
console.log(`Built ${manifest.modules.length} core modules and ${manifest.features.length} features.`);
